"""Write numbers.tex and tasks_table.tex for the Fin-RSI paper from the library itself.

    python paper/latex_acl2027/make_numbers.py

Every count in the library, methods and task sections comes from here, so the paper cannot
drift from the code. The reference-agreement figures are computed, not copied: each task's
independent reference is compared with the one-step library call on every seed.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
SEEDS = (11, 23, 37)
FAMILY_ORDER = ("portfolio", "signal", "volatility", "risk", "forecast")
MODELS = 5                      # planned (design doc section 6); fixed when the protocol freezes


def _sci(x: float) -> str:
    """1.4e-06 -> 1.4\\times10^{-6} (math mode text)."""
    mantissa, exponent = f"{x:.1e}".split("e")
    return f"{mantissa}\\times10^{{{int(exponent)}}}"


def main() -> None:
    from fin_skills import rsi
    from fin_skills.algorithms import catalog
    from fin_skills.api.rules import CARDS, CAUSES
    from fin_skills.tasks import library_positions, panel, reference, suite
    from fin_skills.tasks.spec import FORCED_DEV
    import fin_skills.tools as tools

    idx = json.loads((ROOT / "catalog" / "index.json").read_text())
    algos = catalog()
    native = [a for a in algos if a["library"] == "fin-skills"]
    adapters = [a for a in algos if a["library"] != "fin-skills"]
    guards = tools.list_guards()
    tasks = suite()
    dev_algos = sorted({t.algorithm for t in tasks.dev})
    held_algos = sorted({t.algorithm for t in tasks.heldout})

    worst = {"min_variance": 0.0, "other": 0.0}
    for task in tasks.tasks:
        for seed in SEEDS:
            raw, factors, _ = panel(seed, rows=task.rows, factors=task.factors,
                                    order=task.order)
            got = library_positions(task, raw, factors).to_numpy()
            gap = float(np.max(np.abs(got - reference(task, seed))))
            key = "min_variance" if task.algorithm == "min_variance" else "other"
            worst[key] = max(worst[key], gap)

    budget, fit = rsi.Budget(), rsi.FitBudget()
    evolve = rsi.Evolve()
    rows_e4 = {t.rows for t in tasks.tasks if t.origin == "e4"}
    rows_new = {t.rows for t in tasks.tasks if t.origin != "e4"}
    assert len(rows_e4) == len(rows_new) == 1
    families = {f: [t for t in tasks.tasks if t.family == f] for f in FAMILY_ORDER}
    assert sum(len(v) for v in families.values()) == len(tasks.tasks)

    n = {
        "NSkills": idx["n_skills"], "NPlugins": len(idx["plugins"]),
        "NReferenceFiles": idx["n_reference_files"], "NScripts": idx["n_scripts"],
        "NListingTokens": f"{round(idx['discovery_cost']['approx_tokens'], -2):,}",
        "NAlgorithms": len(algos), "NAlgorithmTasks": len({a["task"] for a in algos}),
        "NNative": len(native), "NAdapters": len(adapters),
        "NOptionalLibraries": len({a["library"] for a in adapters}),
        "NGuards": guards["count"], "NGuardsExported": guards["exported"],
        "NGuardsPythonOnly": guards["excluded"], "NTools": len(tools.tool_names()),
        "NCards": len(CARDS), "NCardFamilies": len({c.family for c in CARDS}),
        "NCauses": len(CAUSES), "NMethods": len(rsi.METHODS), "NArms": len(rsi.ARMS),
        "NTasks": len(tasks.tasks), "NTaskAlgorithms": len({t.algorithm for t in tasks.tasks}),
        "NDevTasks": len(tasks.dev), "NDevAlgorithms": len(dev_algos),
        "NHeldTasks": len(tasks.heldout), "NHeldAlgorithms": len(held_algos),
        "NHeldFamilies": len({t.family for t in tasks.heldout}),
        "NFamilies": len(FAMILY_ORDER), "NSeeds": len(SEEDS),
        "NRows": rows_new.pop(), "NRowsEFour": rows_e4.pop(),
        "NEFourTasks": sum(t.origin == "e4" for t in tasks.tasks),
        "NForcedDev": len(set(FORCED_DEV) & {t.algorithm for t in tasks.tasks}),
        "NDrawn": len({t.algorithm for t in tasks.tasks} - set(FORCED_DEV)),
        "NDrawnDev": len(set(dev_algos) - set(FORCED_DEV)),
        "NModels": MODELS,
        "NMainEpisodes": f"{len(rsi.METHODS) * 2 * len(tasks.heldout) * len(SEEDS) * MODELS:,}",
        "NAblationEpisodes": f"{3 * 2 * len(tasks.heldout) * len(SEEDS) * MODELS:,}",
        "RefGapMinVariance": _sci(worst["min_variance"]),
        "RefGapOther": _sci(worst["other"]),
        "BudgetAttempts": budget.attempts, "BudgetCalls": budget.calls,
        "BudgetTokens": f"{budget.generated_tokens:,}",
        "FitEpisodes": fit.episodes, "FitProposals": fit.proposals,
        "FitCalls": fit.calls, "FitTokens": f"{fit.generated_tokens:,}",
        "EvolveGenerations": evolve.generations, "EvolveMinibatch": evolve.minibatch,
    }
    lines = ["% Generated by make_numbers.py from the library; do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in n.items()]
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n")

    tt = lambda x: "\\texttt{" + x.replace("_", "\\_") + "}"
    call = {"table": tt("rolling()"), "positions": tt("positions()")}
    body = []
    for f in FAMILY_ORDER:
        body.append(f"\\multicolumn{{3}}{{@{{}}l}}{{\\emph{{{f}}}}} \\\\")
        for algorithm in sorted({t.algorithm for t in families[f]}):
            kind = next(t.kind for t in families[f] if t.algorithm == algorithm)
            body.append(f"\\quad {tt(algorithm)} & {tasks.splits[algorithm]} & {call[kind]} \\\\")
    table = ["% Generated by make_numbers.py from fin_skills.tasks; do not edit by hand.",
             "\\begin{tabular}{@{}lll@{}}", "\\toprule",
             "Algorithm & Split & Library call \\\\", "\\midrule", *body,
             "\\bottomrule", "\\end{tabular}"]
    (OUT / "tasks_table.tex").write_text("\n".join(table) + "\n")

    rows = []
    for family in dict.fromkeys(c.family for c in CARDS):
        rows.append(f"\\multicolumn{{3}}{{@{{}}l}}{{\\emph{{{family.replace('_', ' ')}}}}} \\\\")
        for c in (c for c in CARDS if c.family == family):
            checks = " \\newline ".join(tt(k) for k in c.checks)
            rows.append(f"\\quad {tt(c.id)} & {checks} & {'yes' if c.tool else '--'} \\\\")
    cards = ["% Generated by make_numbers.py from fin_skills.api.rules; do not edit by hand.",
             "\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{@{}l>{\\raggedright\\arraybackslash}p{3.0cm}c@{}}",
             "\\toprule", "Card & Verified by & Call \\\\", "\\midrule", *rows,
             "\\bottomrule", "\\end{tabular}"]
    (OUT / "cards_table.tex").write_text("\n".join(cards) + "\n")
    print(json.dumps(n, indent=1))


if __name__ == "__main__":
    main()
