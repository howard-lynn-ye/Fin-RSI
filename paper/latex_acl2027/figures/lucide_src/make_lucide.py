"""Turn the Lucide icons the figures use into TikZ pics (figures/lucide.tex).

Lucide (https://lucide.dev, ISC licence) draws every icon on a 24-unit grid with one stroke
width, round caps and round joins, so the icons match each other. This script reads the SVG
files of `npm install lucide-static`, converts every element to TikZ path operations (arcs to
cubic Beziers, at most a quarter turn each) and writes one pic per icon, `lu <name>`, about
0.3 cm across and centred on the origin. Colour and stroke width come from the \\pic call:

    \\pic[draw=white, line width=0.7pt, scale=0.9] at (x,y) {lu bot};

    python3 make_lucide.py <path to node_modules/lucide-static>
"""
from __future__ import annotations

import math
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

from svgpathtools import Arc, CubicBezier, Line, QuadraticBezier, parse_path

ICONS = ("bot", "lock", "check", "x", "code", "file-check", "shield-check", "refresh-cw",
         "sigma", "database", "gauge", "chart-column", "plug", "square-terminal", "braces",
         "book-open", "file-text", "chart-line", "user")
SIZE = 0.3                                           # cm across the 24-unit grid
U = SIZE / 24
OUT = Path(__file__).resolve().parent.parent / "lucide.tex"


def pt(z: complex) -> str:
    return f"({(z.real - 12) * U:.4f},{(12 - z.imag) * U:.4f})"


def path_ops(d: str) -> list[str]:
    """TikZ path operations for one SVG path, one string per subpath."""
    out, cur, start, last = [], [], None, None
    for seg in parse_path(d):
        if start is None or abs(seg.start - last) > 1e-9:          # a new subpath
            if cur:
                out.append(" ".join(cur))
            cur, start = [pt(seg.start)], seg.start
        if isinstance(seg, Arc):
            n = max(1, math.ceil(abs(seg.delta) / 90 - 1e-9))
            parts = list(seg.as_cubic_curves(curves=n))
        elif isinstance(seg, QuadraticBezier):
            c1 = seg.start + 2 / 3 * (seg.control - seg.start)
            c2 = seg.end + 2 / 3 * (seg.control - seg.end)
            parts = [CubicBezier(seg.start, c1, c2, seg.end)]
        else:
            parts = [seg]
        for p in parts:
            if isinstance(p, Line):
                cur.append("-- " + pt(p.end))
            else:
                cur.append(f".. controls {pt(p.control1)} and {pt(p.control2)} .. {pt(p.end)}")
        last = seg.end
        if abs(last - start) < 1e-9 and len(cur) > 1:
            cur.append("-- cycle")
            out.append(" ".join(cur))
            cur, start = [], None
    if cur:
        out.append(" ".join(cur))
    return out


def element_ops(el: ET.Element) -> list[str]:
    tag = el.tag.split("}")[-1]
    a = {k: float(v) for k, v in el.attrib.items()
         if k in ("x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "x1", "y1", "x2", "y2")}
    if tag == "path":
        return path_ops(el.attrib["d"])
    if tag == "line":
        return [f"{pt(complex(a['x1'], a['y1']))} -- {pt(complex(a['x2'], a['y2']))}"]
    if tag in ("polyline", "polygon"):
        nums = [float(v) for v in re.findall(r"-?[\d.]+", el.attrib["points"])]
        pts = [pt(complex(x, y)) for x, y in zip(nums[::2], nums[1::2])]
        return [" -- ".join(pts) + (" -- cycle" if tag == "polygon" else "")]
    if tag == "circle":
        return [f"{pt(complex(a['cx'], a['cy']))} circle ({a['r'] * U:.4f})"]
    if tag == "ellipse":
        return [f"{pt(complex(a['cx'], a['cy']))} ellipse ({a['rx'] * U:.4f} and {a['ry'] * U:.4f})"]
    if tag == "rect":
        x, y, w, h = a.get("x", 0.0), a.get("y", 0.0), a["width"], a["height"]
        r = a.get("rx", a.get("ry", 0.0))
        corner = f"[rounded corners={r * U:.4f}cm] " if r else ""
        return [f"{corner}{pt(complex(x, y))} rectangle {pt(complex(x + w, y + h))}"]
    raise ValueError(f"unhandled SVG element {tag}")


def main(root: str) -> None:
    root = Path(root)
    licence = (root / "LICENSE").read_text().strip().splitlines()
    version = re.search(r'"version":\s*"([^"]+)"', (root / "package.json").read_text())[1]
    lines = ["% GENERATED by figures/lucide_src/make_lucide.py - do not edit by hand.",
             f"% Icons from Lucide {version} (lucide-static), converted to TikZ paths.", "%"]
    lines += ["% " + l if l else "%" for l in licence]
    lines += ["%", r"\tikzset{%",
              r"  lucide/.style={line width=0.7pt, line cap=round, line join=round},%"]
    for name in ICONS:
        svg = ET.parse(root / "icons" / f"{name}.svg").getroot()
        ops = [op for el in svg if el.tag.split("}")[-1] != "title" for op in element_ops(el)]
        body = " ".join(f"\\draw[lucide, pic actions, fill=none] {op};" for op in ops)
        lines.append(f"  lu {name}/.pic={{{body}}},%")
    lines.append("}%")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(ICONS)} icons -> {OUT.name}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "node_modules/lucide-static")
