"""Figure 1, 3D variant: the same content as compose_kit.py, drawn in oblique 3D.

The library is a cabinet. Its top is a tray with one well per kind of tool, holding the real
counts: a book per skill (grouped by plugin), a card per rule card, a cube per check and a token
per self-improvement method; the engine is on the dark front. The pieces one agent picks are in
colour and arc onto a pedestal where they stand beside the user's model; the agent is used
through MCP, Python or tool schemas. On the right, each task runs on a track: write, check,
improve after a failed check, deliver after a pass, within one equal budget. Labels stay flat.

Oblique projection: screen x = x + K*y, screen y = z + M*y (y is depth). Picks, counts and icons
are those of compose_kit.py; style from figures/figstyle.tex.

    python3 compose_3d.py        # writes ../overview3d.tex
"""
from __future__ import annotations

import math
from pathlib import Path

import compose_kit as kit

n, f = kit.n, kit.f
L: list[str] = []
w = L.append
K, M = 0.38, 0.40
BX, BY = 0.05, 0.42                 # screen position of the cabinet's front-bottom-left corner
CL, CD, CH = 7.2, 5.0, 0.95         # cabinet length, depth, front height
WIDTH = 16.0


def P(x: float, y: float, z: float) -> str:
    return f"({f(BX + x + K * y)},{f(BY + CH + z + M * y)})"


def poly(style: str, *pts) -> None:
    w(f"\\path[{style}] " + " -- ".join(P(*p) for p in pts) + " -- cycle;")


def prism(x, y, z, dx, dy, dz, front, top, side, edge="none", lw=0.3):
    """A box on the cabinet's grid: front face, top face, right face."""
    e = f", draw={edge}, line width={lw}pt, line join=round" if edge != "none" else ""
    poly(f"fill={side}{e}", (x + dx, y, z), (x + dx, y + dy, z), (x + dx, y + dy, z + dz), (x + dx, y, z + dz))
    poly(f"fill={front}{e}", (x, y, z), (x + dx, y, z), (x + dx, y, z + dz), (x, y, z + dz))
    poly(f"fill={top}{e}", (x, y, z + dz), (x + dx, y, z + dz), (x + dx, y + dy, z + dz), (x, y + dy, z + dz))


def screen(x, y, z):
    return BX + x + K * y, BY + CH + z + M * y


def main() -> None:
    w("% GENERATED by figures/overview_src/compose_3d.py - do not edit by hand.")
    w("% Figure 1, 3D variant: the library as a cabinet, the agent on a pedestal, the task track.")
    w(r"\ifcsname figTitleFont\endcsname\else\InputIfFileExists{figures/figstyle}{}{\input{../latex_acl2027/figures/figstyle}}\fi")
    w(r"\begin{tikzpicture}[x=1cm, y=1cm, font=\sffamily,")
    w(r"  name/.style={fig title, anchor=south west},")
    w(r"  verb/.style={fig label, font=\figLabelFont\itshape, text=figmid},")
    w(r"]")
    H = 4.55
    w(f"\\useasboundingbox (0,0) rectangle ({f(WIDTH)},{f(H)});")

    # ------------------------------------------------------------------ the cabinet
    # ground shadow
    w(r"\begin{scope}[transparency group, opacity=0.18]")
    w(f"\\fill[figink, blur shadow={{shadow blur steps=10, shadow xshift=0pt, shadow yshift=0pt, "
      f"shadow blur radius=4pt, shadow opacity=60}}, opacity=0] {P(0.1, 0.25, -CH - 0.02)} -- {P(CL + 0.25, 0.25, -CH - 0.02)} "
      f"-- {P(CL + 0.25, CD + 0.1, -CH - 0.02)} -- {P(0.1, CD + 0.1, -CH - 0.02)} -- cycle;")
    w(r"\end{scope}")
    poly("left color=figink!80, right color=figink!62, draw=figink, line width=0.5pt, line join=round",
         (CL, 0, -CH), (CL, CD, -CH), (CL, CD, 0), (CL, 0, 0))
    x0, y0 = screen(0, 0, -CH)
    x1, y1 = screen(CL, 0, 0)
    w(f"\\path[top color=figink!88, bottom color=figink, draw=figink, line width=0.5pt] ({f(x0)},{f(y0)}) rectangle ({f(x1)},{f(y1)});")
    poly("top color=white, bottom color=figfaint, draw=figink!70, line width=0.6pt, line join=round",
         (0, 0, 0), (CL, 0, 0), (CL, CD, 0), (0, CD, 0))
    # front: brand and engine
    w(f"\\node[anchor=west, font=\\figBrandFont, text=white, inner sep=0] at ({f(x0 + 0.22)},{f(y1 - 0.3)}) {{Fin-RSI}};")
    w(f"\\node[anchor=west, fig note, text=white!70] at ({f(x0 + 0.22)},{f(y0 + 0.24)}) {{engine}};")
    for i, (pic, word) in enumerate((("lu sigma", "algorithms"), ("lu database", "data"),
                                     ("lu gauge", "backtester"), ("lu chart-column", "benchmark"))):
        cx = x0 + 2.35 + i * 1.38
        w(f"\\path[fill=white!14!figink] ({f(cx)},{f(y1 - 0.33)}) circle (0.19);")
        w(f"\\pic[draw=white, line width=0.65pt, scale=0.85] at ({f(cx)},{f(y1 - 0.33)}) {{{pic}}};")
        w(f"\\node[fig small, anchor=base, text=white!85] at ({f(cx)},{f(y0 + 0.13)}) {{{word}}};")

    labels: list[str] = []                # well labels, drawn over the items

    def well(xa, xb, ya, yb, col, title, count):
        poly(f"fill={col}!7, draw={col}!45, line width=0.5pt, line join=round",
             (xa, ya, 0), (xb, ya, 0), (xb, yb, 0), (xa, yb, 0))
        w(f"\\draw[{col}!55, line width=0.9pt, line cap=round, line join=round] {P(xa, ya, 0)} -- {P(xa, yb, 0)} -- {P(xb, yb, 0)};")
        sx, sy = screen(xa + 0.1, ya + 0.12, 0)
        labels.append(f"\\node[name, fill={col}!7, inner xsep=1.5pt, inner ysep=0.8pt, rounded corners=1pt] "
                      f"at ({f(sx - 0.05)},{f(sy - 0.03)}) {{\\textcolor{{{col}!75!black}}{{{title}}}"
                      f"\\hspace{{1.2mm}}\\textcolor{{{col}!55!black}}{{\\fontseries{{m}}\\selectfont {count}}}}};")

    # wells: back row skills; front row rule cards | checks | self-improvement
    well(0.15, CL - 0.15, 2.75, CD - 0.15, "finblue", "skills", n("NSkills"))
    well(0.15, 1.95, 0.15, 2.6, "finblue", "rule cards", n("NCards"))
    well(2.1, 5.3, 0.15, 2.6, "finorange", "checks", n("NGuards"))
    well(5.45, CL - 0.15, 0.15, 2.6, "finaqua", "self-improvement", n("NMethods"))

    picked_at = {}                       # screen anchors of the picked groups, for the arcs
    # skills: one book per skill, grouped by plugin, standing in the back well
    gap = 0.075
    pitch = (CL - 0.75 - (n("NPlugins") - 1) * gap) / n("NSkills")
    x = 0.4
    yb, dd, hb = 3.55, 0.55, 0.5
    xs_pick = []
    for plugin in kit.IDX["plugins"]:
        for _ in range(kit.PER_PLUGIN[plugin]):
            on = plugin == kit.PICK_PLUGIN
            if on:
                xs_pick.append(x)
            prism(x, yb, 0, pitch * 0.8, dd, hb,
                  "finblue" if on else "figline", "finblue!55" if on else "white!55!figline",
                  "finblue!75!black" if on else "figline!80!figmid")
            x += pitch
        x += gap
    picked_at["skills"] = screen((xs_pick[0] + xs_pick[-1]) / 2, yb + dd, hb + 0.05)

    # rule cards: 3 x 2 plaques
    for r in (1, 0):
        for c in range(3):
            i = r * 3 + c
            on = i in kit.PICK_CARDS
            xa, ya = 0.35 + c * 0.53, 1.5 + r * 0.6
            prism(xa, ya, 0, 0.42, 0.45, 0.05, "finblue!80!black" if on else "figline",
                  "finblue!18" if on else "white", "finblue!70!black" if on else "figline",
                  edge="finblue!80" if on else "figline!90!figmid", lw=0.4)
            sx, sy = screen(xa + 0.07, ya + 0.27, 0.05)
            col = "finblue!75" if on else "figline!90!figmid"
            w(f"\\draw[{col}, line width=0.8pt, line cap=round] ({f(sx)},{f(sy)}) -- ({f(sx + 0.3)},{f(sy)}) "
              f"({f(sx - 0.03)},{f(sy - 0.07)}) -- ({f(sx + 0.17)},{f(sy - 0.07)});")

    # checks: 39 cubes, 13 a row, back rows first
    per = 13
    rows = math.ceil(n("NGuards") / per)
    cube_pick = []
    for r in reversed(range(rows)):
        for c in range(per):
            i = r * per + c
            if i >= n("NGuards"):
                continue
            on = i in kit.PICK_CHECKS
            xa, ya = 2.35 + c * 0.225, 1.42 + (rows - 1 - r) * 0.42
            prism(xa, ya, 0, 0.16, 0.26, 0.16, "finorange" if on else "white!70!figline",
                  "finorange!55" if on else "white", "finorange!75!black" if on else "figline",
                  edge="none")
            if on:
                cube_pick.append(screen(xa + 0.08, ya + 0.15, 0.2))
    picked_at["checks"] = cube_pick

    # self-improvement: tokens
    tok = []
    for r, cols in ((1, (5.75, 6.15, 6.55, 6.95)), (0, (5.95, 6.35, 6.75))):
        for cx in cols:
            tok.append((cx, 1.78 + r * 0.55))
    order = sorted(range(len(tok)), key=lambda i: (-tok[i][1], tok[i][0]))   # back first
    for i in order:
        cx, cy = tok[i]
        on = i == kit.PICK_METHOD
        sx, sy = screen(cx, cy, 0)
        side = "finaqua!75!black" if on else "figline"
        topc = "finaqua" if on else "white"
        w(f"\\path[fill={side}] ({f(sx - 0.15)},{f(sy)}) -- ({f(sx - 0.15)},{f(sy + 0.08)}) arc[start angle=180, end angle=360, x radius=0.15, y radius=0.07] "
          f"-- ({f(sx + 0.15)},{f(sy)}) arc[start angle=0, end angle=-180, x radius=0.15, y radius=0.07] -- cycle;")
        w(f"\\path[fill={topc}, draw={'finaqua!80!black' if on else 'figline!90!figmid'}, line width=0.4pt] ({f(sx)},{f(sy + 0.08)}) ellipse (0.15 and 0.07);")
        if on:
            w(f"\\fill[white] ({f(sx)},{f(sy + 0.08)}) ellipse (0.055 and 0.026);")
            picked_at["method"] = (sx, sy + 0.12)

    L.extend(labels)

    # ------------------------------------------------------------------ your agent: a pedestal
    cx, cy, rx, ry, ph = 10.95, 2.02, 1.25, 0.42, 0.34
    w(r"\begin{scope}[transparency group, opacity=0.16]")
    w(f"\\fill[figink] ({f(cx + 0.08)},{f(cy - ph - 0.06)}) ellipse ({f(rx + 0.12)} and {f(ry + 0.06)});")
    w(r"\end{scope}")
    w(f"\\path[left color=figline!70, right color=figline!95!figmid, draw=figline!90!figmid, line width=0.5pt] "
      f"({f(cx - rx)},{f(cy)}) -- ({f(cx - rx)},{f(cy - ph)}) arc[start angle=180, end angle=360, x radius={f(rx)}, y radius={f(ry)}] "
      f"-- ({f(cx + rx)},{f(cy)}) arc[start angle=0, end angle=180, x radius={f(rx)}, y radius={f(ry)}] -- cycle;")
    w(f"\\path[top color=white, bottom color=figfaint, draw=figline!90!figmid, line width=0.5pt] ({f(cx)},{f(cy)}) ellipse ({f(rx)} and {f(ry)});")
    w(f"\\node[fig title] at ({f(cx)},{f(H - 0.18)}) {{your agent}};")
    # the model
    mx, my = cx - 0.5, cy + 0.42
    w(r"\begin{scope}[transparency group, opacity=0.2]")
    w(f"\\fill[figink] ({f(mx + 0.03)},{f(cy + 0.02)}) ellipse (0.3 and 0.1);")
    w(r"\end{scope}")
    w(f"\\path[ball color=figink!80, shading=ball] ({f(mx)},{f(my)}) circle (0.32);")
    w(f"\\pic[draw=white, line width=0.75pt, scale=1.3] at ({f(mx)},{f(my)}) {{lu bot}};")
    w(f"\\node[fig label, anchor=east] at ({f(mx - 0.4)},{f(my + 0.1)}) {{model}};")
    # the picks, standing on the pedestal (local 3D around the pedestal top)
    def pp(x, y, z):
        return cx + x + K * y, cy + z + M * y
    def pprism(x, y, z, dx, dy, dz, front, top, side):
        for face, pts in (("side", [(x + dx, y, z), (x + dx, y + dy, z), (x + dx, y + dy, z + dz), (x + dx, y, z + dz)]),
                          ("front", [(x, y, z), (x + dx, y, z), (x + dx, y, z + dz), (x, y, z + dz)]),
                          ("top", [(x, y, z + dz), (x + dx, y, z + dz), (x + dx, y + dy, z + dz), (x, y + dy, z + dz)])):
            col = dict(side=side, front=front, top=top)[face]
            w(f"\\path[fill={col}] " + " -- ".join(f"({f(a)},{f(b)})" for a, b in (pp(*q) for q in pts)) + " -- cycle;")
    nb = kit.PER_PLUGIN[kit.PICK_PLUGIN]
    for i in range(nb):
        pprism(0.0 + i * 0.042, 0.05, 0, 0.034, 0.4, 0.42, "finblue", "finblue!55", "finblue!75!black")
    target = {"skills": pp(0.38, 0.45, 0.48)}
    for i in range(len(kit.PICK_CARDS)):
        pprism(0.42 + i * 0.36, -0.75, 0, 0.3, 0.42, 0.05, "finblue!80!black", "finblue!18", "finblue!70!black")
        sx, sy = pp(0.47 + i * 0.36, -0.5, 0.05)
        w(f"\\draw[finblue!75, line width=0.8pt, line cap=round] ({f(sx)},{f(sy)}) -- ({f(sx + 0.2)},{f(sy)}) "
          f"({f(sx - 0.02)},{f(sy - 0.06)}) -- ({f(sx + 0.12)},{f(sy - 0.06)});")
    target["cards"] = pp(0.6, -0.55, 0.1)
    tchecks = []
    for i in range(len(kit.PICK_CHECKS)):
        pprism(-0.98 + i * 0.27, -0.72, 0, 0.18, 0.32, 0.18, "finorange", "finorange!55", "finorange!75!black")
        tchecks.append(pp(-0.89 + i * 0.27, -0.56, 0.22))
    target["checks"] = tchecks
    sx, sy = pp(-0.05, -0.62, 0)
    w(f"\\path[fill=finaqua!75!black] ({f(sx - 0.15)},{f(sy)}) -- ({f(sx - 0.15)},{f(sy + 0.08)}) arc[start angle=180, end angle=360, x radius=0.15, y radius=0.07] "
      f"-- ({f(sx + 0.15)},{f(sy)}) arc[start angle=0, end angle=-180, x radius=0.15, y radius=0.07] -- cycle;")
    w(f"\\path[fill=finaqua, draw=finaqua!80!black, line width=0.4pt] ({f(sx)},{f(sy + 0.08)}) ellipse (0.15 and 0.07);")
    w(f"\\fill[white] ({f(sx)},{f(sy + 0.08)}) ellipse (0.055 and 0.026);")
    target["method"] = (sx, sy + 0.12)

    # pick arcs: each picked group flies from its well to the pedestal
    def arc(a, b, col, lift):
        (ax_, ay_), (bx_, by_) = a, b
        w(f"\\draw[{col}, line width=0.8pt, opacity=0.75, -{{Latex[length=1.6mm,width=1.4mm]}}, dash pattern=on 2.6pt off 1.6pt] "
          f"({f(ax_)},{f(ay_)}) .. controls ({f(ax_ + 1.2)},{f(max(ay_, by_) + lift)}) and ({f(bx_ - 1.0)},{f(max(ay_, by_) + lift)}) .. ({f(bx_)},{f(by_)});")
    sx0, sy0 = screen(CL - 0.4, CD - 0.6, 0.75)
    w(f"\\draw[figmid!75, line width=1.1pt, -{{Latex[length=1.9mm,width=1.7mm]}}] ({f(sx0)},{f(sy0)}) "
      f".. controls ({f(sx0 + 0.9)},{f(sy0 + 0.45)}) and ({f(cx - 0.5)},{f(cy + 1.5)}) .. ({f(cx + 0.05)},{f(cy + 0.95)});")
    w(f"\\node[verb] at ({f(sx0 + 0.95)},{f(sy0 - 0.3)}) {{pick}};")
    # use it from
    w(f"\\node[fig note, fill=white, inner xsep=2pt] at ({f(cx)},0.92) {{use it from}};")
    w(f"\\draw[figline, line width=0.6pt] ({f(cx - rx)},0.92) -- ({f(cx + rx)},0.92);")
    for i, (pic, word) in enumerate((("lu plug", "MCP"), ("lu square-terminal", "Python"), ("lu braces", "schemas"))):
        ix = cx - 1.0 + i * 1.0
        w(f"\\path[fill=figmid!14] ({f(ix)},0.55) circle (0.17);")
        w(f"\\pic[draw=figmid, line width=0.65pt, scale=0.75] at ({f(ix)},0.55) {{{pic}}};")
        w(f"\\node[fig small, anchor=base] at ({f(ix)},0.12) {{{word}}};")

    # ------------------------------------------------------------------ on each task: a track
    w(f"\\draw[fig flow, line width=1.1pt] ({f(cx + rx + 0.2)},{f(cy)}) -- ({f(cx + rx + 0.75)},{f(cy)});")
    w(f"\\node[verb] at ({f(cx + rx + 0.47)},{f(cy + 0.25)}) {{run}};")
    tx, ty, trx, try_ = 14.45, 1.62, 1.12, 0.46
    w(f"\\node[fig title, anchor=west] at ({f(tx - trx - 0.25)},{f(H - 0.18)}) {{on each task}};")
    w(f"\\draw[figline!70, line width=7pt] ({f(tx)},{f(ty)}) ellipse ({f(trx)} and {f(try_)});")
    w(f"\\draw[white, line width=0.6pt, dash pattern=on 3pt off 3pt] ({f(tx)},{f(ty)}) ellipse ({f(trx)} and {f(try_)});")

    def ang(a):                              # point on the track at angle a (degrees)
        return tx + trx * math.cos(math.radians(a)), ty + try_ * math.sin(math.radians(a))

    def track_arrow(a0, a1, style):
        w(f"\\draw[{style}] ({f(ang(a0)[0])},{f(ang(a0)[1])}) arc[start angle={a0}, end angle={a1}, "
          f"x radius={f(trx)}, y radius={f(try_)}];")

    track_arrow(150, 32, "fig flow")
    track_arrow(-30, -72, "fig fail")
    track_arrow(-110, -155, "fig back")

    def puck(px, py, col, pic, word, above=True):
        w(r"\begin{scope}[transparency group, opacity=0.18]")
        w(f"\\fill[figink] ({f(px + 0.03)},{f(py - 0.04)}) ellipse (0.36 and 0.13);")
        w(r"\end{scope}")
        w(f"\\path[fill={col}!75!black] ({f(px - 0.32)},{f(py)}) -- ({f(px - 0.32)},{f(py + 0.16)}) arc[start angle=180, end angle=360, x radius=0.32, y radius=0.13] "
          f"-- ({f(px + 0.32)},{f(py)}) arc[start angle=0, end angle=-180, x radius=0.32, y radius=0.13] -- cycle;")
        w(f"\\path[top color={col}!80, bottom color={col}] ({f(px)},{f(py + 0.16)}) ellipse (0.32 and 0.13);")
        w(f"\\path[fill={col}] ({f(px)},{f(py + 0.48)}) circle (0.25);")
        w(f"\\pic[draw=white, line width=0.75pt, scale=1.05] at ({f(px)},{f(py + 0.48)}) {{{pic}}};")
        if above:
            w(f"\\node[fig label, anchor=base] at ({f(px)},{f(py + 0.85)}) {{{word}}};")
        else:
            w(f"\\node[fig label, anchor=base] at ({f(px)},{f(py - 0.46)}) {{{word}}};")

    wx, wy = ang(180)
    kx, ky = ang(0)
    ix, iy = ang(-90)
    puck(wx, wy - 0.1, "finblue", "lu code", "write", above=False)
    puck(kx, ky - 0.1, "finorange", "lu shield-check", "check", above=False)
    puck(ix, iy - 0.12, "finaqua", "lu refresh-cw", "improve", above=False)
    # verdict marks on the track
    fx, fy = ang(-52)
    w(f"\\pic[draw=figbad, line width=0.85pt, scale=0.55] at ({f(fx - 0.14)},{f(fy + 0.16)}) {{lu x}};")
    # pass: up to deliver
    dx_, dy_ = kx - 0.05, ty + 1.75
    w(f"\\draw[fig pass] ({f(kx)},{f(ky + 0.78)}) -- ({f(dx_)},{f(dy_ - 0.3)});")
    w(f"\\pic[draw=figok, line width=0.85pt, scale=0.6] at ({f(kx + 0.2)},{f((ky + 0.78 + dy_ - 0.3) / 2)}) {{lu check}};")
    w(f"\\path[fill=figink, fig shadow] ({f(dx_)},{f(dy_)}) circle (0.25);")
    w(f"\\pic[draw=white, line width=0.75pt, scale=1.05] at ({f(dx_)},{f(dy_)}) {{lu file-check}};")
    w(f"\\node[fig label, anchor=east] at ({f(dx_ - 0.33)},{f(dy_)}) {{deliver}};")
    # budget
    bx0 = WIDTH - 2.9
    for i in range(n("BudgetAttempts")):
        on = i < 2
        w(f"\\path[fill={'figink!55' if on else 'white'}, draw=figink!55, line width=0.5pt] ({f(bx0 + i * 0.22)},0.2) circle (0.07);")
    w(f"\\node[fig small, anchor=west] at ({f(bx0 + 0.6)},0.2) {{equal budget: {n('BudgetAttempts')} runs}};")
    w(r"\end{tikzpicture}")
    k = next(i for i, line in enumerate(L) if line.startswith(r"\begin{tikzpicture}"))
    L[:k] = [line + "%" for line in L[:k]]
    (kit.HERE.parent / "overview3d.tex").write_text("\n".join(L) + "\n")
    print(f"3D figure {WIDTH} x {H} cm")


if __name__ == "__main__":
    main()
