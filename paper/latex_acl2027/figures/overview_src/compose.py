"""Figure 1: compose the rendered layers into ../overview.tex.

Run after `node scene.cjs` and `node panel.cjs`. It crops the three perspective layers to their
common extent, writes them next to the panel in ../overview/, and writes a TikZ picture that stacks
them with the threads drawn between layers (so each plane covers the part of a thread that runs
behind it), the zoom wedge, the highlights on the panel and the numbered labels.

    python3 compose.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "overview"
DSF = 4                      # device scale factor used by the renders
SCENE_W = 8.75               # cm, the perspective view
GAP = 0.30                   # cm between the view and the panel
PANEL_W = 8.0                # cm
TOP = 0.42                   # cm reserved above the panel for its label


def crop_layers() -> tuple[tuple[int, int, int, int], tuple[int, int]]:
    raws = [Image.open(OUT / f"raw_p{i}.png").convert("RGBA") for i in range(3)]
    box = None
    for im in raws:
        b = im.getchannel("A").point(lambda a: 255 if a > 6 else 0).getbbox()
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    pad = 8 * DSF
    box = (max(0, box[0] - pad), max(0, box[1] - pad), box[2] + pad, box[3] + pad)
    size = None
    for i, im in enumerate(raws):
        c = im.crop(box)
        c = c.resize((c.width // 2, c.height // 2), Image.LANCZOS)
        c.save(OUT / f"l{i}.png", optimize=True)
        size = c.size
    panel = Image.open(OUT / "panel.png").convert("RGBA")
    panel.resize((panel.width // 2, panel.height // 2), Image.LANCZOS).save(OUT / "panel_s.png", optimize=True)
    return box, size


def main() -> None:
    a = json.loads((HERE / "anchors.json").read_text())
    pa = json.loads((HERE / "panel_anchors.json").read_text())
    box, _ = crop_layers()
    bx, by = box[0] / DSF, box[1] / DSF
    s = SCENE_W / ((box[2] - box[0]) / DSF)               # cm per css px
    scene_h = (box[3] - box[1]) / DSF * s
    panel_h = PANEL_W * pa["H"] / pa["W"]
    height = max(scene_h, panel_h + TOP + 0.55)
    y0 = height - scene_h                                  # scene sits at the bottom-left
    px0 = SCENE_W + GAP
    py_top = height - TOP                                  # panel top edge
    ps = PANEL_W / pa["W"]

    def S(pt):                                             # scene css px -> tikz cm
        return (pt[0] - bx) * s, y0 + scene_h - (pt[1] - by) * s

    def B(name, side="c"):                                 # panel element box -> tikz cm
        x, y, w, h = pa["boxes"][name]
        x0, y1 = px0 + x * ps, py_top - y * ps
        x1, y2 = x0 + w * ps, y1 - h * ps
        return {"c": ((x0 + x1) / 2, (y1 + y2) / 2), "box": (x0, y2, x1, y1), "w": (x0, (y1 + y2) / 2)}[side]

    P = a["pts"]
    f = lambda v: f"{v:.4f}"
    xy = lambda p: f"({f(p[0])},{f(p[1])})"
    L = []
    w = L.append
    w("% GENERATED by figures/overview_src/compose.py from scene.cjs and panel.cjs renders - do not edit by hand.")
    w("% Figure 1: the AMZN 20-for-1 split runs from the information feeds, through the rule card and the")
    w("% check that cover it, into the line of the agent's program that applies split factors.")
    w(r"\definecolor{thread}{HTML}{2A78D6}\definecolor{glow}{HTML}{6FB0EE}\definecolor{you}{HTML}{7952AA}")
    w(r"\definecolor{inkf}{HTML}{1F2335}")
    w(r"\begin{tikzpicture}[x=1cm, y=1cm, font=\sffamily,")
    w(r"  num/.style={circle, fill=#1, text=white, font=\sffamily\tiny\bfseries, inner sep=0pt, minimum size=3.1mm},")
    w(r"  tag/.style={anchor=west, inner sep=1pt, fill=white, fill opacity=0.85, text opacity=1, text=#1,")
    w(r"               font=\sffamily\fontsize{6.4}{7.4}\selectfont\bfseries},")
    w(r"  hint/.style={anchor=west, inner sep=0pt, text=inkf!65, font=\sffamily\fontsize{5.4}{6.4}\selectfont},")
    w(r"]")
    w(f"\\path (0,0) rectangle ({f(px0 + PANEL_W)},{f(height)});")

    # zoom wedge from the agent's windows to the panel
    wr, wb = S(a["win"][0]), S(a["win"][1])
    pl_top, pl_bot = (px0, py_top), (px0, py_top - panel_h)
    w(f"\\shade[left color=thread!30, right color=thread!5, fill opacity=0.55] {xy(wr)} -- {xy(pl_top)} -- {xy(pl_bot)} -- {xy(wb)} -- cycle;")
    w(f"\\draw[thread!28, line width=0.35pt] {xy(wr)} -- {xy(pl_top)} {xy(wb)} -- {xy(pl_bot)};")

    img = lambda name: w(f"\\node[anchor=north west, inner sep=0] at (0,{f(height)}) "
                         f"{{\\includegraphics[width={SCENE_W}cm]{{figures/overview/{name}}}}};")

    def thread(p, q, col, n=10, glowing=True):
        if glowing:
            w(f"\\draw[glow!55, line width=2.1pt, line cap=round, opacity=0.7] {xy(p)} -- {xy(q)};")
        for i in range(n):
            t0, t1 = i / n, (i + 1) / n
            a0 = (p[0] + (q[0] - p[0]) * t0, p[1] + (q[1] - p[1]) * t0)
            a1 = (p[0] + (q[0] - p[0]) * t1, p[1] + (q[1] - p[1]) * t1)
            mix = min(100, int(20 + 110 * t1))
            w(f"\\draw[{col}!{mix}!glow, line width=0.8pt, line cap=round] {xy(a0)} -- {xy(a1)};")

    amzn, card, check, line = S(P["t-amzn"]), S(P["g-card"]), S(P["g-check"]), S(P["c-line"])
    img("l0.png")
    thread(amzn, card, "thread")
    thread(amzn, check, "finorange", glowing=False)
    img("l1.png")
    thread(card, line, "thread")
    thread(check, line, "finorange", glowing=False)
    img("l2.png")
    w(f"\\fill[glow, fill opacity=0.28] {xy(line)} circle (0.17);")
    w(f"\\fill[glow, fill opacity=0.28] {xy(amzn)} circle (0.2);")

    # the panel
    x1, y1 = px0 + PANEL_W, py_top - panel_h
    w(f"\\path[blur shadow={{shadow blur steps=10, shadow xshift=0pt, shadow yshift=-1.2pt, shadow opacity=24, "
      f"shadow blur radius=3pt}}, fill=white, rounded corners=3pt] ({f(px0)},{f(y1)}) rectangle ({f(x1)},{f(py_top)});")
    w(f"\\node[anchor=north west, inner sep=0] at ({f(px0)},{f(py_top)}) {{\\includegraphics[width={PANEL_W}cm]{{figures/overview/panel_s.png}}}};")
    w(f"\\draw[inkf!30, line width=0.4pt, rounded corners=3pt] ({f(px0)},{f(y1)}) rectangle ({f(x1)},{f(py_top)});")
    bx0, by0, bx1, by1 = B("p-check", "box")
    w(f"\\draw[thread, line width=0.8pt, rounded corners=1.6pt] ({f(bx0 - 0.04)},{f(by0 - 0.04)}) rectangle ({f(bx1 + 0.04)},{f(by1 + 0.04)});")

    # numbered labels
    def label(k, col, at, text, hint=None):
        w(f"\\node[num={col}] (n{k}) at {xy(at)} {{{k}}};")
        w(f"\\node[tag={col}] (t{k}) at ([xshift=0.5mm]n{k}.east) {{{text}}};")
        if hint:
            w(f"\\node[hint] at ([xshift=0.6mm]t{k}.east) {{{hint}}};")

    c0 = S(a["corners"]["p0"][3])
    c1 = S(a["corners"]["p1"][3])
    c2 = S(a["win"][4])
    label(1, "inkf", (4.35, 0.22), "Information", "market data, filings, news, macro series")
    label(2, "thread", (0.16, S(a["corners"]["p1"][0])[1] + 0.14), "Skills and checks")
    label(3, "thread", (0.16, c2[1] + 0.62), "Agent program")
    label(4, "inkf", (px0 + 0.12, height - 0.18), "Compose", "one model, then your choices")
    w(r"\end{tikzpicture}")
    (HERE.parent / "overview.tex").write_text("\n".join(L) + "\n")
    print(f"scene {SCENE_W:.2f} x {scene_h:.2f} cm, panel {PANEL_W:.2f} x {panel_h:.2f} cm, figure {px0 + PANEL_W:.2f} x {height:.2f} cm")


if __name__ == "__main__":
    main()
