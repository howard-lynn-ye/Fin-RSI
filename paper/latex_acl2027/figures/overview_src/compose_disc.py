"""Figure 1: compose the dial render into ../overview.tex.

Run after `node disc.cjs`. The disc and its pins come from the render; this draws, in TikZ, the
user's model as the pedestal at the centre, the threads from the chosen pegs into the agent, the
ring names, the information coming in on the left and the interfaces going out on the right.

    python3 compose_disc.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "overview"
DSF = 4
DISC_W = 8.7          # cm
DISC_X = 3.15         # cm, left edge of the disc image
RIGHT_X = 13.55       # cm, the interface icons


def main() -> None:
    a = json.loads((HERE / "disc_anchors.json").read_text())
    im = Image.open(OUT / "raw_disc.png").convert("RGBA")
    box = im.getchannel("A").point(lambda v: 255 if v > 6 else 0).getbbox()
    pad = 6 * DSF
    box = (box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad)
    c = im.crop(box)
    c.resize((c.width // 2, c.height // 2), Image.LANCZOS).save(OUT / "disc.png", optimize=True)
    bx, by = box[0] / DSF, box[1] / DSF
    s = DISC_W / ((box[2] - box[0]) / DSF)
    disc_h = (box[3] - box[1]) / DSF * s
    height = disc_h + 0.75                                  # room above for the agent
    def S(p):
        return DISC_X + (p[0] - bx) * s, disc_h - (p[1] - by) * s

    f = lambda v: f"{v:.4f}"
    xy = lambda p: f"({f(p[0])},{f(p[1])})"
    L = []
    w = L.append
    w("% GENERATED by figures/overview_src/compose_disc.py from the disc.cjs render - do not edit by hand.")
    w("% Figure 1: the library as a dial. Pin counts are the real counts; lit pegs are one agent's choices.")
    w(r"\definecolor{inkf}{HTML}{1F2335}\definecolor{lil}{HTML}{6B5CA5}\definecolor{sla}{HTML}{4C6378}")
    w(r"\begin{tikzpicture}[x=1cm, y=1cm, font=\sffamily,")
    w(r"  word/.style={font=\sffamily\fontsize{6.4}{7.6}\selectfont, text=inkf!80, inner sep=0},")
    w(r"  ring/.style={font=\sffamily\fontsize{6.4}{7.6}\selectfont\bfseries, text=#1!80!black, inner sep=0.8pt,")
    w(r"               fill=white, fill opacity=0.8, text opacity=1, rounded corners=1pt},")
    w(r"  head/.style={font=\sffamily\fontsize{6.4}{7.6}\selectfont\bfseries, text=#1, inner sep=0},")
    w(r"]")
    w(f"\\path (0,0) rectangle (17.5,{f(height)});")
    w(f"\\node[anchor=south west, inner sep=0] at ({f(DISC_X)},0) {{\\includegraphics[width={DISC_W}cm]{{figures/overview/disc.png}}}};")

    # ring names, on the disc at the left front of each ring
    names = {"method": ("finaqua", "self-improvement"), "check": ("finorange", "checks"),
             "skill": ("finblue", "skills"), "template": ("finmagenta", "investor templates")}
    for key, (col, text) in names.items():
        p = S(a["ring"][key]["front"])
        w(f"\\node[ring={col}] at {xy(p)} {{{text}}};")

    # the user's model: a pedestal at the centre
    cx, cy = S(a["centre"])
    rx = abs(S(a["axis"]["x"])[0] - cx)
    ry = abs(S(a["axis"]["y"])[1] - cy)
    h = 0.34
    w(f"\\fill[black, opacity=0.18] ({f(cx + 0.05)},{f(cy - 0.04)}) ellipse ({f(rx * 1.05)} and {f(ry * 1.05)});")
    w(f"\\shade[left color=inkf!88, right color=inkf, middle color=inkf!70] ({f(cx - rx)},{f(cy)}) arc[start angle=180, end angle=360, "
      f"x radius={f(rx)}, y radius={f(ry)}] -- ({f(cx + rx)},{f(cy + h)}) arc[start angle=0, end angle=180, x radius={f(rx)}, "
      f"y radius={f(ry)}] -- cycle;")
    w(f"\\fill[inkf!62] ({f(cx)},{f(cy + h)}) ellipse ({f(rx)} and {f(ry)});")
    w(f"\\node[font=\\sffamily\\fontsize{{6.2}}{{7}}\\selectfont\\bfseries, text=white, inner sep=0] at ({f(cx)},{f(cy - ry * 0.55 + h / 2)}) {{your model}};")

    # threads from the chosen pegs into the agent, above the pedestal
    agent = (cx, cy + h + 1.05)
    for m in a["pegs_meta"]:
        p = S(a["pegs"][m["id"]])
        col = {"method": "finaqua", "check": "finorange", "skill": "finblue", "template": "finmagenta"}[m["ring"]]
        side = agent[0] + (p[0] - agent[0]) * 0.32
        path = (f"{xy(p)} .. controls ({f(p[0])},{f(p[1] + 0.9)}) and ({f(side)},{f(agent[1] - 0.05)}) .. "
                f"({f(agent[0] + (p[0] - agent[0]) * 0.06)},{f(agent[1] - 0.12)})")
        w(f"\\draw[{col}!35, line width=1.8pt, line cap=round, opacity=0.6] {path};")
        w(f"\\draw[{col}, line width=0.7pt, line cap=round] {path};")
        w(f"\\fill[{col}] {xy(p)} circle (0.03);")
    w(f"\\draw[inkf!50, line width=0.7pt] ({f(cx)},{f(cy + h)}) -- ({f(agent[0])},{f(agent[1] - 0.16)});")
    w(f"\\node[fill=inkf, text=white, rounded corners=3pt, inner xsep=5pt, inner ysep=2.6pt, "
      f"font=\\sffamily\\fontsize{{7}}{{8}}\\selectfont\\bfseries, blur shadow={{shadow blur steps=6, shadow yshift=-0.8pt, shadow opacity=25}}] "
      f"(agent) at {xy(agent)} {{agent}};")

    # information in, on the left
    rim = S(a["rim"]["180"])
    w(f"\\node[head=lil, anchor=west] at (0.0,{f(disc_h - 0.35)}) {{information}};")
    info = [("fin chart", "prices"), ("fin doc", "filings"), ("fin feed", "news"), ("fin search", "search")]
    ys = [disc_h - 0.95 - i * 0.78 for i in range(len(info))]
    for (icon, word), y in zip(info, ys):
        w(f"\\fill[lil!14] (0.22,{f(y)}) circle (0.2);")
        w(f"\\pic[draw=lil, fill=lil, line width=0.55pt, scale=0.85] at (0.22,{f(y)}) {{{icon}}};")
        w(f"\\node[word, anchor=west] at (0.52,{f(y)}) {{{word}}};")
        w(f"\\draw[lil!40, line width=0.8pt] (1.45,{f(y)}) .. controls (2.3,{f(y)}) and ({f(rim[0] - 0.8)},{f(rim[1])}) .. ({f(rim[0] - 0.12)},{f(rim[1])});")
    w(f"\\draw[-{{Latex[length=1.6mm,width=1.4mm]}}, lil!60, line width=0.8pt] ({f(rim[0] - 0.2)},{f(rim[1])}) -- ({f(rim[0] + 0.08)},{f(rim[1])});")

    # interfaces out, on the right
    outs = [("fin plug", "MCP"), ("fin code", "Python API"), ("fin plug", "OpenAI tools"), ("fin plug", "Anthropic tools"),
            ("fin link", "bridges"), ("fin gauge", "backtester"), ("fin check", "benchmark")]
    top = height - 0.3
    w(f"\\node[head=sla, anchor=west] at ({f(RIGHT_X - 0.22)},{f(top)}) {{interfaces}};")
    step = (top - 0.45) / len(outs)
    for i, (icon, word) in enumerate(outs):
        y = top - 0.5 - i * step
        w(f"\\draw[sla!40, line width=0.75pt] (agent.east) .. controls ({f(agent[0] + 2.6)},{f(agent[1])}) and ({f(RIGHT_X - 1.4)},{f(y)}) .. ({f(RIGHT_X - 0.28)},{f(y)});")
        w(f"\\fill[sla!14] ({f(RIGHT_X)},{f(y)}) circle (0.2);")
        w(f"\\pic[draw=sla, fill=sla, line width=0.55pt, scale=0.85] at ({f(RIGHT_X)},{f(y)}) {{{icon}}};")
        w(f"\\node[word, anchor=west] at ({f(RIGHT_X + 0.3)},{f(y)}) {{{word}}};")
    w(r"\end{tikzpicture}")
    (HERE.parent / "overview.tex").write_text("\n".join(L) + "\n")
    print(f"disc {DISC_W:.2f} x {disc_h:.2f} cm, figure 17.5 x {height:.2f} cm")


if __name__ == "__main__":
    main()
