"""Figure 1: what is in Fin-RSI and how an agent uses it, in shapes rather than words.

Left, the library is one toolbox with a handle. Each compartment holds one glyph per item, in the
real counts: one spine per skill, grouped by plugin; one card per rule card; one square per check
(pick any); one disc per self-improvement method (pick one); and the engine underneath. Middle,
one agent is the user's model plus the pieces it picked, which are filled in the box; it is reached
through MCP, tool schemas or the Python API. Right, on each task the agent writes a program, the
checks run, and a failed check goes to the self-improvement method before the next attempt; a
program that passes is delivered. Stage colours are the compartment colours. Words are only the
compartment names and one word per stage.

Drawn at the ACL text width (16 cm) so no version scales it, with no text below 7 pt. The
federated investor templates are left out: they are off by default and not verified here.

Writes ../overview.tex (pure TikZ). Counts come from ../../numbers.tex and catalog/index.json.

    python3 compose_kit.py
"""
from __future__ import annotations

import collections
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
NUM = {m[1]: m[2] for m in re.finditer(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}",
                                        (HERE.parent.parent / "numbers.tex").read_text())}
n = lambda k: int(NUM[k].replace(",", ""))
IDX = json.loads((ROOT / "catalog" / "index.json").read_text())
PER_PLUGIN = collections.Counter(s["plugin"] for s in IDX["skills"])

L: list[str] = []
w = L.append
f = lambda v: f"{v:.3f}"

# One agent's picks, by name; the glyph positions follow the library's own order.
import sys  # noqa: E402
sys.path.insert(0, str(ROOT))
from fin_skills import rsi, tools  # noqa: E402
from fin_skills.api import rules  # noqa: E402

GUARDS = [g["guard"] for g in tools.list_guards()["guards"]]
CARD_IDS = [c.id for c in rules.CARDS]
METHOD_NAMES = [m.name for m in rsi.METHODS]
PICK_METHOD = METHOD_NAMES.index("playbook")
PICK_CHECKS = {GUARDS.index(g) for g in ("execution_lag", "adjustment_check", "warmup_probe")}
PICK_PLUGIN = "fin-core"
PICK_CARDS = {CARD_IDS.index(c) for c in ("execution_lag", "split_once")}
WIDTH = 16.0                         # cm, the ACL text width


def comp(x, y_top, wdt, hgt, col, title, count):
    w(f"\\path[fill={col}!6, draw={col}!35, line width=0.5pt, rounded corners=2.5pt] "
      f"({f(x)},{f(y_top - hgt)}) rectangle ({f(x + wdt)},{f(y_top)});")
    w(f"\\node[name] at ({f(x + 0.13)},{f(y_top - 0.2)}) {{\\textcolor{{{col}!75!black}}{{{title}}}"
      f"\\hspace{{1.2mm}}\\textcolor{{{col}!55!black}}{{\\fontseries{{m}}\\selectfont {count}}}}};")


def main() -> None:
    assert sum(PER_PLUGIN.values()) == n("NSkills") and len(PER_PLUGIN) == n("NPlugins")
    assert len(GUARDS) == n("NGuards") and len(CARD_IDS) == n("NCards")
    assert len(METHOD_NAMES) == n("NMethods")
    w("% GENERATED by figures/overview_src/compose_kit.py - do not edit by hand.")
    w("% Figure 2: Fin-RSI as a toolbox; one glyph per item, filled glyphs are one agent's picks.")
    w(r"% Colours, text, lines, corners, shadows and icons: figures/figstyle.tex.")
    w(r"\ifcsname figTitleFont\endcsname\else\InputIfFileExists{figures/figstyle}{}{\input{../latex_acl2027/figures/figstyle}}\fi")
    w(r"\begin{tikzpicture}[x=1cm, y=1cm, font=\sffamily,")
    w(r"  name/.style={fig title, anchor=west},")
    w(r"  word/.style={fig label},")
    w(r"  head/.style={fig title, anchor=west, text=#1},")
    w(r"  bigarrow/.style={fill=figink!11, draw=none},")
    w(r"  verb/.style={fig label, font=\figLabelFont\itshape, text=figmid},")
    w(r"]")
    H = 4.45
    w(f"\\useasboundingbox (0,0) rectangle ({f(WIDTH)},{f(H)});")

    # glyphs
    def disc(x, y, on, k=1.0):
        if on:
            w(f"\\fill[finaqua] ({f(x)},{f(y)}) circle ({f(0.13 * k)}); \\fill[white] ({f(x)},{f(y)}) circle ({f(0.05 * k)});")
        else:
            w(f"\\draw[koff, line width=0.6pt] ({f(x)},{f(y)}) circle (0.12);")

    def square(x, y, on, s=0.085):
        if on:
            k = s / 0.085
            w(f"\\fill[finorange, rounded corners=0.6pt] ({f(x - s)},{f(y - s)}) rectangle ({f(x + s)},{f(y + s)});")
            w(f"\\draw[white, line width={f(0.55 * k)}pt, line cap=round, line join=round] ({f(x - 0.045 * k)},{f(y)}) -- "
              f"({f(x - 0.012 * k)},{f(y - 0.035 * k)}) -- ({f(x + 0.05 * k)},{f(y + 0.04 * k)});")
        else:
            w(f"\\draw[koff, line width=0.5pt, rounded corners=0.6pt] ({f(x - s + 0.01)},{f(y - s + 0.01)}) rectangle ({f(x + s - 0.01)},{f(y + s - 0.01)});")

    def spine(x, y, on, h=0.42, wd=0.034):
        col = "finblue" if on else "koff"
        w(f"\\fill[{col}] ({f(x)},{f(y)}) rectangle ({f(x + wd)},{f(y + h)});")

    def card(x, y, on=True, k=1.0):
        col, fill = ("finblue", "finblue!14") if on else ("koff", "white")
        w(f"\\path[fill={fill}, draw={col}, line width=0.55pt, rounded corners=1pt] "
          f"({f(x - 0.17 * k)},{f(y - 0.12 * k)}) rectangle ({f(x + 0.17 * k)},{f(y + 0.12 * k)});")
        w(f"\\draw[{col}, line width=0.75pt, line cap=round] ({f(x - 0.1 * k)},{f(y + 0.04 * k)}) -- "
          f"({f(x + 0.1 * k)},{f(y + 0.04 * k)}) ({f(x - 0.1 * k)},{f(y - 0.04 * k)}) -- "
          f"({f(x + 0.04 * k)},{f(y - 0.04 * k)});")

    def big(x0, x1, yc, hh=0.5):
        w(f"\\path[bigarrow] ({f(x0)},{f(yc - hh / 2)}) -- ({f(x1 - 0.2)},{f(yc - hh / 2)}) -- ({f(x1 - 0.2)},{f(yc - hh / 2 - 0.15)}) "
          f"-- ({f(x1)},{f(yc)}) -- ({f(x1 - 0.2)},{f(yc + hh / 2 + 0.15)}) -- ({f(x1 - 0.2)},{f(yc + hh / 2)}) -- ({f(x0)},{f(yc + hh / 2)}) -- cycle;")

    def icon(cx, cy, col, pic, r=0.2, k=0.85, solid=False):
        if solid:
            w(f"\\path[fill={col}] ({f(cx)},{f(cy)}) circle ({f(r)});")
            w(f"\\pic[draw=white, line width=0.75pt, scale={f(k)}] at ({f(cx)},{f(cy)}) {{{pic}}};")
        else:
            w(f"\\path[fill={col}!14] ({f(cx)},{f(cy)}) circle ({f(r)});")
            w(f"\\pic[draw={col}, line width=0.65pt, scale={f(k)}] at ({f(cx)},{f(cy)}) {{{pic}}};")

    # ------------------------------------------------------------------ the toolbox
    bx, bw, top = 0.02, 8.5, H - 0.34
    w(f"\\draw[kink!70, line width=2.2pt, line cap=round, rounded corners=3pt] ({f(bx + bw / 2 - 1.1)},{f(top)}) -- "
      f"({f(bx + bw / 2 - 1.1)},{f(top + 0.28)}) -- ({f(bx + bw / 2 + 1.1)},{f(top + 0.28)}) -- ({f(bx + bw / 2 + 1.1)},{f(top)});")
    w(f"\\path[fill=white, draw=figink!80, line width=0.9pt, rounded corners=4pt, fig shadow] "
      f"({f(bx)},0) rectangle ({f(bx + bw)},{f(top)});")
    w(f"\\begin{{scope}}\\clip[rounded corners=4pt] ({f(bx)},0) rectangle ({f(bx + bw)},{f(top)});")
    w(f"\\fill[kink] ({f(bx)},{f(top - 0.46)}) rectangle ({f(bx + bw)},{f(top)});\\end{{scope}}")
    w(f"\\node[anchor=west, font=\\figBrandFont, text=white, inner sep=0] "
      f"at ({f(bx + 0.22)},{f(top - 0.23)}) {{Fin-RSI}};")

    g, pad = 0.14, 0.15
    ws = bw - 2 * pad
    w1 = 2.72                                  # left column of rows 2 and 3
    # row 1: skills, one spine per skill, grouped by plugin
    r1, h1 = top - 0.46 - g, 0.98
    comp(bx + pad, r1, ws, h1, "finblue", "skills", n("NSkills"))
    pitch, gap = 0.052, 0.074
    width = n("NSkills") * pitch + (n("NPlugins") - 1) * gap
    x = bx + pad + (ws - width) / 2
    for plugin in IDX["plugins"]:
        for _ in range(PER_PLUGIN[plugin]):
            spine(x, r1 - 0.86, plugin == PICK_PLUGIN)
            x += pitch
        x += gap
    # row 2: rule cards | checks
    r2, h2 = r1 - h1 - g, 1.0
    comp(bx + pad, r2, w1, h2, "finblue", "rule cards", n("NCards"))
    for i in range(n("NCards")):
        card(bx + pad + 0.34 + i * 0.41, r2 - 0.64, i in PICK_CARDS)
    x2, w2 = bx + pad + w1 + g, ws - w1 - g
    comp(x2, r2, w2, h2, "finorange", "checks", n("NGuards"))
    per_row = 20
    for i in range(n("NGuards")):
        r, c = divmod(i, per_row)
        square(x2 + 0.24 + c * 0.245, r2 - 0.52 - r * 0.28, i in PICK_CHECKS)
    # row 3: self-improvement | engine
    r3 = r2 - h2 - g
    h3 = r3 - pad
    comp(bx + pad, r3, w1, h3, "finaqua", "self-improvement", n("NMethods"))
    for i in range(n("NMethods")):
        disc(bx + pad + 0.32 + i * 0.34, r3 - 0.64, i == PICK_METHOD)
    xe, we = x2, w2
    comp(xe, r3, we, h3, "fingray", "engine", "")
    for i, (pic, word) in enumerate((("lu sigma", "algorithms"), ("lu database", "data"),
                                     ("lu gauge", "backtester"), ("lu chart-column", "benchmark"))):
        cx = xe + 0.75 + i * (we - 1.5) / 3
        icon(cx, r3 - 0.56, "fingray", pic)
        w(f"\\node[fig small, anchor=base] at ({f(cx)},{f(r3 - 0.98)}) {{{word}}};")

    # ------------------------------------------------------------------ your agent
    ax, aw = bx + bw + 0.72, 2.85
    big(bx + bw + 0.04, ax - 0.04, 2.55)
    w(f"\\node[verb] at ({f(bx + bw + 0.36)},{f(3.07)}) {{pick}};")
    w(f"\\path[fig box] ({f(ax)},1.2) rectangle ({f(ax + aw)},{f(top)});")
    w(f"\\node[head=kink] at ({f(ax + 0.14)},{f(top - 0.24)}) {{your agent}};")
    mx, my = ax + aw / 2 - 0.3, top - 0.84
    w(f"\\path[fill=kink] ({f(mx)},{f(my)}) circle (0.3);")
    w(f"\\pic[draw=white, line width=0.75pt, scale=1.3] at ({f(mx)},{f(my)}) {{lu bot}};")
    w(f"\\node[word, anchor=west] at ({f(mx + 0.38)},{f(my)}) {{model}};")
    w(f"\\node[fig title, text=figink!45] at ({f(mx)},{f(my - 0.47)}) {{+}};")
    py = my - 0.82                             # the picks, larger
    nsp = PER_PLUGIN[PICK_PLUGIN]
    row = nsp * 0.07 + 0.08 + 0.4 + 0.42 * len(PICK_CARDS) - 0.2       # spines, gap, cards
    x0 = ax + (aw - row) / 2
    for i in range(nsp):
        spine(x0 + i * 0.07, py - 0.2, True, h=0.42, wd=0.042)
    cxs = x0 + nsp * 0.07 + 0.08
    for i in range(len(PICK_CARDS)):
        card(cxs + 0.2 + i * 0.42, py + 0.01, True)
    qy = py - 0.52
    for i in range(len(PICK_CHECKS)):
        square(x0 + 0.12 + i * 0.34, qy, True, s=0.12)
    disc(x0 + 0.12 + len(PICK_CHECKS) * 0.34 + 0.12, qy, True, k=1.2)
    # reached from
    for i, (pic, word) in enumerate((("lu plug", "MCP"), ("lu square-terminal", "Python"), ("lu braces", "schemas"))):
        cx = ax + 0.4 + i * (aw - 0.8) / 2
        icon(cx, 0.72, "kuse", pic, r=0.19, k=0.8)
        w(f"\\node[fig small, anchor=base] at ({f(cx)},{f(0.29)}) {{{word}}};")
    w(f"\\draw[kink!30, line width=0.6pt] ({f(ax + 0.12)},1.04) -- ({f(ax + aw - 0.12)},1.04);")
    w(f"\\node[fig note, fill=white, inner xsep=2pt] "
      f"at ({f(ax + aw / 2)},1.04) {{use it from}};")

    # ------------------------------------------------------------------ on each task
    lx = ax + aw + 0.72
    big(ax + aw + 0.04, lx - 0.04, 2.55)
    w(f"\\node[verb] at ({f(ax + aw + 0.36)},{f(3.07)}) {{run}};")
    w(f"\\node[head=kink] at ({f(lx + 0.02)},{f(top - 0.24)}) {{on each task}};")
    arrow = "-{Latex[length=1.6mm,width=1.4mm]}"
    xw, xc, xi, xd = lx + 0.34, lx + 1.5, lx + 0.92, WIDTH - 0.32
    yt, yb = top - 1.15, top - 2.5
    icon(xw, yt, "finblue", "lu code", r=0.3, k=1.25, solid=True)
    icon(xc, yt, "finorange", "lu shield-check", r=0.3, k=1.25, solid=True)
    icon(xi, yb, "finaqua", "lu refresh-cw", r=0.3, k=1.25, solid=True)
    icon(xd, yt, "figink", "lu file-check", r=0.3, k=1.25, solid=True)
    for x, y, word in ((xw, yt, "write"), (xc, yt, "check"), (xd, yt, "deliver")):
        w(f"\\node[word, anchor=base] at ({f(x)},{f(y + 0.42)}) {{{word}}};")
    w(f"\\node[word, anchor=base] at ({f(xi)},{f(yb - 0.6)}) {{improve}};")
    w(f"\\draw[{arrow}, kink!45, line width=0.8pt] ({f(xw + 0.34)},{f(yt)}) -- ({f(xc - 0.34)},{f(yt)});")
    w(f"\\draw[{arrow}, gbad!80, line width=0.8pt] ({f(xc - 0.1)},{f(yt - 0.36)}) -- ({f(xi + 0.24)},{f(yb + 0.27)});")
    w(f"\\draw[{arrow}, finaqua!85!black, line width=0.8pt] ({f(xi - 0.24)},{f(yb + 0.27)}) -- ({f(xw + 0.1)},{f(yt - 0.36)});")
    w(f"\\draw[{arrow}, gok, line width=0.8pt] ({f(xc + 0.34)},{f(yt)}) -- ({f(xd - 0.34)},{f(yt)});")
    # the verdict marks on the two exits from check
    w(f"\\path[fill=white] ({f((xc + xi) / 2 + 0.17)},{f((yt + yb) / 2 + 0.04)}) circle (0.12);")
    w(f"\\draw[gbad, line width=0.9pt, line cap=round] ({f((xc + xi) / 2 + 0.11)},{f((yt + yb) / 2 - 0.02)}) -- "
      f"({f((xc + xi) / 2 + 0.23)},{f((yt + yb) / 2 + 0.1)}) ({f((xc + xi) / 2 + 0.11)},{f((yt + yb) / 2 + 0.1)}) -- "
      f"({f((xc + xi) / 2 + 0.23)},{f((yt + yb) / 2 - 0.02)});")
    mxv = (xc + xd) / 2
    w(f"\\draw[gok, line width=0.9pt, line cap=round, line join=round] ({f(mxv - 0.08)},{f(yt + 0.17)}) -- "
      f"({f(mxv - 0.02)},{f(yt + 0.11)}) -- ({f(mxv + 0.09)},{f(yt + 0.25)});")
    # the budget: at most three runs
    for i in range(n("BudgetAttempts")):
        on = i < 2                                 # two used, as in Figure 2
        w(f"\\path[fill={'kink!55' if on else 'white'}, draw=kink!55, line width=0.5pt] "
          f"({f(lx + 0.12 + i * 0.22)},0.72) circle (0.07);")
    w(f"\\node[fig small, anchor=west] at ({f(lx + 0.72)},0.72) {{equal budget: {n("BudgetAttempts")} runs}};")
    w(r"\end{tikzpicture}")
    k = next(i for i, line in enumerate(L) if line.startswith(r"\begin{tikzpicture}"))
    L[:k] = [line + "%" for line in L[:k]]
    (HERE.parent / "overview.tex").write_text("\n".join(l for l in L if l is not None) + "\n")
    print(f"figure {WIDTH} x {H:.2f} cm")


if __name__ == "__main__":
    main()
